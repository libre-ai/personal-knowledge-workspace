use std::error::Error;
use std::fs;
use std::io::ErrorKind;
use std::path::Path;

/// Environment variables the build refuses. `tauri-build` (`TAURI_CONFIG`, merged
/// into the parsed configuration), and `generate_context!` after it, apply them on
/// top of `tauri.conf.json`, while the static gate (`tests/shell/config.test.ts`)
/// reads the tracked files only. A build under one of them is therefore not the
/// shell the gate judged: `{"app":{"security":{"csp":null}}}` drops the CSP (C3),
/// and an inline capability on every window with `core:default` compiles although
/// `capabilities/` holds none (C2, C5). `tests/shell/build-env.test.ts` replays both.
///
/// The Tauri CLI hands its overrides to the build through this variable (`tauri dev`,
/// `tauri build --config`), so those commands are refused here as well. The shell is
/// developed by rebuilding the front (`bun run --cwd apps/desktop build`) and running
/// `cargo run -p libre-ai-p04-desktop`: the default `custom-protocol` feature makes
/// that binary serve the embedded front like the release one, and `devUrl` stays out
/// of `tauri.conf.json`. A dev server would need its own decision (a feature or a
/// separate crate judged by the same gate), not an exception to this list.
///
/// `tests/shell/refuse-env.ts` reads this list to refuse the same names before the
/// first cargo step of `check:p04-shell`.
const REFUSED_ENV: &[&str] = &["TAURI_CONFIG"];

/// The only commands the front can call. `AppManifest::commands` makes
/// tauri-build generate one `allow-<command>` permission per name; a command
/// registered in the handler but absent here has no permission and is refused.
/// `capabilities/main.json` lists the same names, and `tests/shell/config.test.ts`
/// fails on any drift between the two.
const COMMANDS: &[&str] = &[
    "shell_ping",
    "open_vault",
    "read_note",
    "write_note",
    "render_preview",
    "search",
    "rebuild_index",
];

/// tauri-build writes one `<command>.toml` per command of `COMMANDS` into this
/// gitignored directory and never deletes the file of a removed command: its
/// permission would stay in the vocabulary of the rebuilt binary (measured:
/// `allow-probe-old` still in `gen/schemas/` after `probe_old` left `COMMANDS`).
/// Only the stale files go. Clearing the whole directory would rewrite it at every
/// run, and tauri-build watches `permissions/`: the crate would rebuild on every
/// cargo call.
fn remove_stale_permissions(directory: &Path) -> Result<(), Box<dyn Error>> {
    let entries = match fs::read_dir(directory) {
        Ok(entries) => entries,
        Err(error) if error.kind() == ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(format!("cannot read {}: {error}", directory.display()).into()),
    };
    for entry in entries {
        let path = entry?.path();
        let current = path
            .file_stem()
            .and_then(|stem| stem.to_str())
            .is_some_and(|stem| COMMANDS.contains(&stem));
        if !current {
            fs::remove_file(&path)?;
        }
    }
    Ok(())
}

fn main() -> Result<(), Box<dyn Error>> {
    for name in REFUSED_ENV {
        // Cargo reruns the script when the variable appears or changes; a cached
        // build made under a clean environment would otherwise stay green.
        println!("cargo::rerun-if-env-changed={name}");
        if std::env::var_os(name).is_some() {
            return Err(format!(
                "{name} is set: tauri-build would merge it into the configuration, so this shell would not be built from the files that apps/desktop/tests/shell/config.test.ts judged (controls C2 to C5: it can drop the CSP or compile a capability absent from capabilities/). Unset it; `tauri dev` and `tauri build --config` set it, so they are refused too"
            )
            .into());
        }
    }

    // `generate_context!` embeds `frontendDist`; without it the failure is a
    // proc-macro panic that does not say how to build the front.
    if !Path::new("../dist/index.html").is_file() {
        return Err(
            "apps/desktop/dist/index.html is missing: run `bun run --cwd apps/desktop build`"
                .into(),
        );
    }
    println!("cargo::rerun-if-changed=../dist");
    println!("cargo::rerun-if-changed=build.rs");

    remove_stale_permissions(Path::new("permissions/autogenerated"))?;

    let attributes = tauri_build::Attributes::new()
        .app_manifest(tauri_build::AppManifest::new().commands(COMMANDS));
    tauri_build::try_build(attributes)?;
    Ok(())
}
